//! `unused-local`: a local variable whose value is never read.
//!
//! ```papyrus
//! Function F()
//!     Int count = Count()   ; `count` is never read
//! EndFunction
//! ```
//!
//! Fix: removes the declaration. An initial value with a call stays as a
//! statement, for its effects.
//!
//! ```papyrus
//! Int unused = 1              ; removed
//! Int unused = Count()        ; → Count()
//! ```

use papyrus_ide::{
    Diagnostic,
    assists::{Assist, AssistCtx, AssistKind, TextEdit, line_range},
    hir::{Body, Expr, LocalId, Stmt},
    sema::Sema,
};
use papyrus_parser::{
    SyntaxKind,
    ast::{self, AstNode},
};

use crate::{Group, Lint, bodies};

const CODE: &str = "unused-local";

pub(crate) const LINT: Lint = Lint {
    code: CODE,
    group: Group::Suspicious,
    summary: "a local variable whose value is never read",
    run,
    fix: Some(fix),
};

fn run(sema: &Sema<'_>, out: &mut Vec<Diagnostic>) {
    // Fragments generated by the Creation Kit declare `akSpeaker`,
    // `kmyQuest`... whether the code uses them or not.
    if sema.text.contains(";BEGIN FRAGMENT CODE") {
        return;
    }
    for body in bodies(sema) {
        for local in unread_locals(&body) {
            let data = body.local(local);
            out.push(Diagnostic::warning(
                data.range,
                CODE,
                format!("`{}` is never read", data.name),
            ));
        }
    }
}

/// The local variables (not parameters) of `body` whose value is never read.
fn unread_locals(body: &Body) -> Vec<LocalId> {
    let mut read = vec![false; body.locals.len()];
    // Targets of `=` are writes; every other use is a read (`x += 1` too).
    let mut targets = vec![false; body.exprs.len()];
    for (stmt, _) in &body.stmts {
        if let Stmt::Assign { op: None, target, .. } = stmt {
            targets[target.0 as usize] = true;
        }
    }
    for (i, (expr, _)) in body.exprs.iter().enumerate() {
        if let Expr::Local(LocalId(l)) = expr
            && !targets[i]
        {
            read[*l as usize] = true;
        }
    }
    (0..body.locals.len())
        .filter(|&l| !body.locals[l].is_param && !read[l])
        .map(|l| LocalId(l as u32))
        .collect()
}

fn fix(ctx: &AssistCtx<'_>, acc: &mut Vec<Assist>) {
    let Some(var) = ctx.find_node::<ast::VarDecl<'_>>() else { return };
    // Locals only: script variables are not in a block.
    if var.syntax().parent().is_none_or(|p| p.kind() != SyntaxKind::BLOCK) {
        return;
    }
    let Some(name) = var.name() else { return };
    let func = var
        .syntax()
        .ancestors()
        .find(|n| matches!(n.kind(), SyntaxKind::FUNCTION | SyntaxKind::EVENT));
    let Some(body) = func.and_then(|f| Body::lower(ctx.sema, f)) else { return };
    let range = name.syntax().text_range();
    if !unread_locals(&body).into_iter().any(|l| body.local(l).range == range) {
        return;
    }
    let decl = var.syntax().trimmed_range();
    let edit = match var.initializer() {
        Some(init) if has_call(init) => {
            TextEdit { range: decl, new_text: ctx.text(init.syntax()).to_owned() }
        }
        _ => TextEdit { range: line_range(ctx.sema.text, decl), new_text: String::new() },
    };
    acc.push(Assist {
        id: "remove_unused_local",
        label: format!("Remove the unused variable `{}`", name.text()),
        kind: AssistKind::QuickFix,
        target: decl,
        edits: vec![edit],
        fixes: Some(CODE),
    });
}

fn has_call(expr: ast::Expr<'_>) -> bool {
    std::iter::once(expr.syntax())
        .chain(expr.syntax().descendants())
        .any(|n| n.kind() == SyntaxKind::CALL_EXPR)
}

#[cfg(test)]
mod tests {
    use papyrus_ide::assists::test_utils::{check_assist, check_assist_not_applicable};

    use super::fix;
    use crate::test_utils::check;

    #[test]
    fn reports_locals_never_read() {
        let src = "ScriptName T\nInt Function F(Int unusedParam)\n    Int a = 1\n    Int b\n    b = 2\n    Int c = 3\n    c += 1\n    Int d = 4\n    Return d\nEndFunction\n";
        assert_eq!(check("unused-local", src), ["3: `a` is never read", "4: `b` is never read"]);
    }

    #[test]
    fn fix_removes_the_line() {
        check_assist(
            fix,
            "ScriptName T\nFunction F()\n    Int $0a = 1\n    Debug.Trace(\"x\")\nEndFunction\n",
            "ScriptName T\nFunction F()\n    Debug.Trace(\"x\")\nEndFunction\n",
        );
    }

    #[test]
    fn fix_keeps_calls() {
        check_assist(
            fix,
            "ScriptName T\nInt Function G()\n    Return 1\nEndFunction\nFunction F()\n    Int $0a = G()\nEndFunction\n",
            "ScriptName T\nInt Function G()\n    Return 1\nEndFunction\nFunction F()\n    G()\nEndFunction\n",
        );
    }

    #[test]
    fn no_fix_when_read() {
        check_assist_not_applicable(
            fix,
            "ScriptName T\nInt Function F()\n    Int $0a = 1\n    Return a\nEndFunction\n",
        );
    }
}
